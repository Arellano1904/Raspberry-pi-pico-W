static void ili9341_cmd(uint8_t cmd, const uint8_t *params, size_t len)
{
    cs_select();

    gpio_put(ILI9341_PIN_DC, 0);  // Command phase
    spi_write_blocking(ILI9341_SPI_PORT, &cmd, 1);

    if (len > 0) {
        gpio_put(ILI9341_PIN_DC, 1);  // Data phase
        spi_write_blocking(ILI9341_SPI_PORT, params, len);
    }

    cs_deselect();
}

// Pulse the reset line low to put the controller into a known state.
static void ili9341_hw_reset(void)
{
    gpio_put(ILI9341_PIN_RST, 1);
    sleep_ms(5);
    gpio_put(ILI9341_PIN_RST, 0);
    sleep_ms(20);
    gpio_put(ILI9341_PIN_RST, 1);
    sleep_ms(150);
}

void ili9341_init(void)
{
    // Bring up the SPI bus and the chip-select line.
    spi0_init();

    // Configure the control GPIOs (CS is already set up by spi0_init).
    gpio_init(ILI9341_PIN_DC);
    gpio_set_dir(ILI9341_PIN_DC, GPIO_OUT);

    gpio_init(ILI9341_PIN_RST);
    gpio_set_dir(ILI9341_PIN_RST, GPIO_OUT);

    gpio_init(ILI9341_PIN_BL);
    gpio_set_dir(ILI9341_PIN_BL, GPIO_OUT);
    gpio_put(ILI9341_PIN_BL, 0);  // Backlight off until the panel is ready

    ili9341_hw_reset();

    // Power-on / timing tuning (extended, undocumented registers).
    ili9341_cmd(0xEF, (const uint8_t[]){0x03, 0x80, 0x02}, 3);
    ili9341_cmd(0xCF, (const uint8_t[]){0x00, 0xC1, 0x30}, 3);
    ili9341_cmd(0xED, (const uint8_t[]){0x64, 0x03, 0x12, 0x81}, 4);
    ili9341_cmd(0xE8, (const uint8_t[]){0x85, 0x00, 0x78}, 3);
    ili9341_cmd(0xCB, (const uint8_t[]){0x39, 0x2C, 0x00, 0x34, 0x02}, 5);
    ili9341_cmd(0xF7, (const uint8_t[]){0x20}, 1);
    ili9341_cmd(0xEA, (const uint8_t[]){0x00, 0x00}, 2);

    // Power / VCOM control.
    ili9341_cmd(CMD_PWCTR1, (const uint8_t[]){0x23}, 1);
    ili9341_cmd(CMD_PWCTR2, (const uint8_t[]){0x10}, 1);
    ili9341_cmd(CMD_VMCTR1, (const uint8_t[]){0x3E, 0x28}, 2);
    ili9341_cmd(CMD_VMCTR2, (const uint8_t[]){0x86}, 1);

    // Memory access order: landscape, RGB colour order (320x240).
    ili9341_cmd(CMD_MADCTL, (const uint8_t[]){0x36}, 1);
    // 16 bits/pixel (RGB565).
    ili9341_cmd(CMD_PIXFMT, (const uint8_t[]){0x55}, 1);

    // Frame rate and display function control.
    ili9341_cmd(CMD_FRMCTR1, (const uint8_t[]){0x00, 0x18}, 2);
    ili9341_cmd(CMD_DFUNCTR, (const uint8_t[]){0x08, 0x82, 0x27}, 3);

    // Gamma configuration.
    ili9341_cmd(0xF2, (const uint8_t[]){0x00}, 1);          // 3Gamma off
    ili9341_cmd(CMD_GAMMASET, (const uint8_t[]){0x01}, 1);  // Gamma curve 1
    ili9341_cmd(CMD_GMCTRP1, (const uint8_t[]){
        0x0F, 0x31, 0x2B, 0x0C, 0x0E, 0x08, 0x4E, 0xF1,
        0x37, 0x07, 0x10, 0x03, 0x0E, 0x09, 0x00}, 15);
    ili9341_cmd(CMD_GMCTRN1, (const uint8_t[]){
        0x00, 0x0E, 0x14, 0x03, 0x11, 0x07, 0x31, 0xC1,
        0x48, 0x08, 0x0F, 0x0C, 0x31, 0x36, 0x0F}, 15);

    // Exit sleep, then enable the display.
    ili9341_cmd(CMD_SLPOUT, NULL, 0);
    sleep_ms(120);
    ili9341_cmd(CMD_DISPON, NULL, 0);

    // Panel is configured: turn the backlight on.
    gpio_put(ILI9341_PIN_BL, 1);
}

uint32_t spi0_init(void)
{
    // Bring up SPI0 at the requested baud rate (20 MHz).
    uint32_t baud = spi_init(ILI9341_SPI_PORT, ILI9341_SPI_BAUD);

    // Route the SPI0 signals to their GPIOs.
    gpio_set_function(ILI9341_PIN_MISO, GPIO_FUNC_SPI);  // GPIO 16 - RX
    gpio_set_function(ILI9341_PIN_SCK,  GPIO_FUNC_SPI);  // GPIO 18 - SCK
    gpio_set_function(ILI9341_PIN_MOSI, GPIO_FUNC_SPI);  // GPIO 19 - TX

    // Drive chip select manually so the display stays selected across
    // multi-byte command/data transfers (GPIO 17, active low).
    gpio_init(ILI9341_PIN_CS);
    gpio_set_dir(ILI9341_PIN_CS, GPIO_OUT);
    gpio_put(ILI9341_PIN_CS, 1);  // Deselected

    return baud;
}

// Set the GRAM rectangle that subsequent pixel writes target (inclusive
// coordinates). Leaves the controller ready for the caller to start RAMWR.
static void ili9341_set_window(uint16_t x0, uint16_t y0, uint16_t x1, uint16_t y1)
{
    uint8_t caset[] = { x0 >> 8, x0 & 0xFF, x1 >> 8, x1 & 0xFF };
    uint8_t paset[] = { y0 >> 8, y0 & 0xFF, y1 >> 8, y1 & 0xFF };

    ili9341_cmd(CMD_CASET, caset, 4);
    ili9341_cmd(CMD_PASET, paset, 4);
}

// Set the window, then issue RAMWR while keeping CS asserted and DC=data so
// the caller can stream pixel data straight after (the controller's write
// pointer must not be interrupted by another command).
static void ili9341_begin_pixels(uint16_t x0, uint16_t y0, uint16_t x1, uint16_t y1)
{
    ili9341_set_window(x0, y0, x1, y1);

    cs_select();
    gpio_put(ILI9341_PIN_DC, 0);  // Command
    uint8_t ramwr = CMD_RAMWR;
    spi_write_blocking(ILI9341_SPI_PORT, &ramwr, 1);
    gpio_put(ILI9341_PIN_DC, 1);  // Data
}

// Stream `count` RGB565 pixels to the panel via a single DMA request. When
// `incr` is true the source advances through a buffer; when false it stays
// fixed on one colour word (constant fill). Requires ili9341_begin_pixels()
// to have been called first; does not release CS.
static void ili9341_dma_pixels(const void *src, uint32_t count, bool incr)
{
    // Claim a DMA channel on first use.
    if (dma_chan < 0) {
        dma_chan = dma_claim_unused_channel(true);
    }

    // 16-bit frames so each DMA transfer pushes one pixel; the SSP shifts the
    // halfword out MSB-first, matching the panel's byte order.
    spi_set_format(ILI9341_SPI_PORT, 16, SPI_CPOL_0, SPI_CPHA_0, SPI_MSB_FIRST);

    dma_channel_config c = dma_channel_get_default_config(dma_chan);
    channel_config_set_transfer_data_size(&c, DMA_SIZE_16);
    channel_config_set_read_increment(&c, incr);
    channel_config_set_write_increment(&c, false);
    channel_config_set_dreq(&c, spi_get_dreq(ILI9341_SPI_PORT, true));

    dma_channel_configure(
        dma_chan, &c,
        &spi_get_hw(ILI9341_SPI_PORT)->dr,  // Destination: SPI TX FIFO
        src,                                // Source: colour word or buffer
        count,                              // One transfer per pixel
        true);                              // Start immediately

    dma_channel_wait_for_finish_blocking(dma_chan);

    // Let the SSP drain its FIFO before changing format / releasing CS.
    while (spi_is_busy(ILI9341_SPI_PORT)) {
        tight_loop_contents();
    }

    // Restore 8-bit frames for normal command/data writes.
    spi_set_format(ILI9341_SPI_PORT, 8, SPI_CPOL_0, SPI_CPHA_0, SPI_MSB_FIRST);
}

void ili9341_fill_screen(uint16_t color)
{
    ili9341_begin_pixels(0, 0, ILI9341_WIDTH - 1, ILI9341_HEIGHT - 1);
    ili9341_dma_pixels(&color, (uint32_t)ILI9341_WIDTH * ILI9341_HEIGHT, false);
    cs_deselect();
}

// font8x16 geometry: 8 px wide (one byte/row, MSB = leftmost), 16 rows,
// indexed from ASCII 0x20 (space).
#define FONT_W           8
#define FONT_H           16
#define FONT_FIRST_CHAR  0x20
#define FONT_LAST_CHAR   0x7E

// The widest line one DMA request paints in a single shot: a full screen row.
#define MAX_CHARS_PER_LINE (ILI9341_WIDTH / FONT_W)  // 240 / 8 = 30

void ili9341_print_string(uint16_t x, uint16_t y, const char *str,
                          uint16_t fg, uint16_t bg)
{
    // One contiguous frame for the whole line, sent with a single DMA request.
    static uint16_t line_buf[MAX_CHARS_PER_LINE * FONT_W * FONT_H];

    if (x >= ILI9341_WIDTH || y >= ILI9341_HEIGHT) {
        return;
    }

    // Print as many characters as fit from x to the right edge, capped at the
    // most a single DMA line buffer holds.
    size_t max_fit = (ILI9341_WIDTH - x) / FONT_W;
    if (max_fit > MAX_CHARS_PER_LINE) {
        max_fit = MAX_CHARS_PER_LINE;
    }

    size_t n = 0;
    while (str[n] != '\0' && n < max_fit) {
        n++;
    }
    if (n == 0) {
        return;
    }

    uint16_t stride = (uint16_t)(n * FONT_W);  // Pixels per row in the buffer

    // Rasterise each glyph into the line buffer, laid out row-major to match
    // the address window (row 0 first, left to right).
    for (size_t i = 0; i < n; i++) {
        unsigned char ch = (unsigned char)str[i];
        if (ch < FONT_FIRST_CHAR || ch > FONT_LAST_CHAR) {
            ch = FONT_FIRST_CHAR;  // Unsupported glyphs render as a space
        }
        const unsigned char *glyph = font8x16[ch - FONT_FIRST_CHAR];

        for (uint8_t row = 0; row < FONT_H; row++) {
            unsigned char bits = glyph[row];
            uint16_t *dst = &line_buf[(size_t)row * stride + i * FONT_W];
            for (uint8_t col = 0; col < FONT_W; col++) {
                dst[col] = (bits & (0x80 >> col)) ? fg : bg;
            }
        }
    }

    // Push the whole rendered line in one DMA request.
    ili9341_begin_pixels(x, y, x + stride - 1, y + FONT_H - 1);
    ili9341_dma_pixels(line_buf, (uint32_t)stride * FONT_H, true);
    cs_deselect();
}

void ili9341_print_int(uint16_t x, uint16_t y, int value, uint16_t fg, uint16_t bg)
{
    char buf[16];  // Enough for -2147483648 plus terminator
    snprintf(buf, sizeof(buf), "%d", value);
    ili9341_print_string(x, y, buf, fg, bg);
}

void ili9341_print_float(uint16_t x, uint16_t y, float value, uint8_t decimals,
                         uint16_t fg, uint16_t bg)
{
    char buf[32];
    if (decimals > 7) {
        decimals = 7;  // Clamp so the formatted value cannot overflow buf
    }
    snprintf(buf, sizeof(buf), "%.*f", (int)decimals, (double)value);
    ili9341_print_string(x, y, buf, fg, bg);
}
